#!/usr/bin/env node
/*
 * Emits lesson-hashes.js — a short content hash for every lesson .md file.
 *
 * The app stores the hash of each lesson at the moment you mark it complete.
 * On a later visit, a differing hash means the lesson genuinely changed since
 * you read it, so it can be flagged as worth re-reading.
 *
 * A hash (rather than a timestamp) is deliberate: file mtimes change on every
 * clone and checkout, which would flag the entire course as "updated" for
 * everyone after any deploy. Hashing the bytes only changes when the words do.
 *
 * Run via `npm run build`, or directly: node generate-lesson-hashes.js
 */
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { fileURLToPath } from 'url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const appJs = fs.readFileSync(path.join(ROOT, 'app.js'), 'utf8');
const m = appJs.match(/const PATHS = \[[\s\S]*?\n\];/);
if (!m) throw new Error('Could not find PATHS array in app.js');
const PATHS = new Function(m[0] + '; return PATHS;')();

const hashes = {};
let counted = 0, missing = 0;
for (const p of PATHS) {
  for (const s of p.subs) {
    const file = path.join(ROOT, 'course', p.id, s.id + '.md');
    if (!fs.existsSync(file)) { missing++; continue; }
    // Normalise line endings so a CRLF/LF difference isn't reported as a
    // content change to readers.
    const body = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
    hashes[`${p.id}/${s.id}`] = crypto.createHash('sha1').update(body).digest('hex').slice(0, 10);
    counted++;
  }
}

const out = `/* AUTO-GENERATED by generate-lesson-hashes.js — do not hand-edit.
   Short content hash per lesson, used to detect lessons that changed
   after a reader completed them. Run \`node generate-lesson-hashes.js\`. */

const LESSON_HASHES = ${JSON.stringify(hashes, null, 1)};
`;
fs.writeFileSync(path.join(ROOT, 'lesson-hashes.js'), out);
console.log(`lesson-hashes.js written — ${counted} lessons hashed${missing ? `, ${missing} missing file(s) skipped` : ''}.`);
