#!/usr/bin/env node
/*
 * Regenerates glossary.js from every lesson's "## Key terms" section.
 * Run this after adding or editing lessons' key terms:
 *   node generate-glossary.js
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));

const appJs = fs.readFileSync(path.join(ROOT, 'app.js'), 'utf8');
const m = appJs.match(/const PATHS = \[[\s\S]*?\n\];/);
if (!m) throw new Error('Could not find PATHS array in app.js');
const PATHS = new Function(m[0] + '; return PATHS;')();

const TERM_RE = /^- \*\*(.+?)\*\* — (.+)$/;

const entries = [];
for (const p of PATHS) {
  for (const s of p.subs) {
    const file = path.join(ROOT, 'course', p.id, s.id + '.md');
    if (!fs.existsSync(file)) continue;
    const text = fs.readFileSync(file, 'utf8');
    const start = text.indexOf('\n## Key terms');
    if (start === -1) continue;
    let body = text.slice(start + '\n## Key terms'.length);
    for (const stop of ['\n## ', '\n???refs']) {
      const i = body.indexOf(stop);
      if (i !== -1) body = body.slice(0, i);
    }
    for (const line of body.split('\n')) {
      const t = line.trim().match(TERM_RE);
      if (!t) continue;
      entries.push({
        term: t[1].trim(),
        def: t[2].trim(),
        pathId: p.id,
        pathN: p.n,
        pathTitle: p.title,
        subId: s.id,
        subTitle: s.title,
      });
    }
  }
}

// Sort alphabetically, case/format-insensitively, for the A-Z listing.
entries.sort((a, b) => a.term.toLowerCase().replace(/[^a-z0-9]/g, '').localeCompare(b.term.toLowerCase().replace(/[^a-z0-9]/g, '')));

const out = `/* AUTO-GENERATED by generate-glossary.js — do not hand-edit.
   Every entry comes from a lesson's "## Key terms" section.
   Run \`node generate-glossary.js\` after editing lessons. */

const GLOSSARY = ${JSON.stringify(entries, null, 1)};
`;

fs.writeFileSync(path.join(ROOT, 'glossary.js'), out);
console.log(`glossary.js written — ${entries.length} terms from ${new Set(entries.map(e => e.pathId + '/' + e.subId)).size} lessons.`);
