#!/usr/bin/env node
/*
 * Regenerates sw.js's precache list from the PATHS array in app.js.
 * Run this after adding/removing/renaming any path or lesson:
 *   node generate-sw.js
 */
import fs from 'fs';
import path from 'path';
import { createHash } from 'crypto';
import { fileURLToPath } from 'url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const appJs = fs.readFileSync(path.join(ROOT, 'app.js'), 'utf8');
const m = appJs.match(/const PATHS = \[[\s\S]*?\n\];/);
if (!m) throw new Error('Could not find PATHS array in app.js');
const PATHS = new Function(m[0] + '; return PATHS;')();

const lessonUrls = [];
for (const p of PATHS) {
  for (const s of p.subs) {
    lessonUrls.push(`course/${p.id}/${s.id}.md`);
  }
}

const shellUrls = [
  './',
  'index.html',
  'styles.css',
  'app.js',
  'quizzes.js',
  'lesson-hashes.js',
  'lesson-updated.js',
  'sync.js',
  'speed-insights.js',
  'analytics.js',
  'web-analytics.js',
  'ads.js',
  // The markdown renderer is vendored rather than pulled from a CDN, so it
  // belongs in the blocking shell precache: without it no lesson can render,
  // offline or on a network that blocks third-party CDNs.
  'vendor/marked.min.js',
  'vendor/purify.min.js',
  // Lazily loaded, but precached so the certificate and transcript still
  // produce a PDF when the user is offline.
  'pdf.js',
  'manifest.json',
  'favicon.svg',
  'icons/icon-192.png',
  'icons/icon-512.png',
  'icons/icon-maskable-512.png',
  'icons/apple-touch-icon.png',
];

// Big, feature-specific bundles load and cache only when requested. An install
// must not silently download all lessons or search data on mobile data.
const deferredUrls = [
  'glossary.js',
  'vendor/cvss4/worker.js',
  'vendor/cvss4/cvss_config.js',
  'vendor/cvss4/metrics.js',
  'vendor/cvss4/cvss_lookup.js',
  'vendor/cvss4/max_composed.js',
  'vendor/cvss4/max_severity.js',
  'vendor/cvss4/cvss_score.js',
  // Lazily loaded on #/tasks.
  'tasks.js',
  'investigations.js',
  'playground.js',
  'learning-guide.js',
  'search-preview.js',
  'search-index.js',
];

// Derive the cache version from the actual shell and deferred assets. A
// hand-maintained number let deployed updates keep serving stale app.js.
// Lesson content remains stale-while-revalidate and does not force a full
// course download on every editorial change.
const cacheHash = createHash('sha256');
for (const url of [...shellUrls, ...deferredUrls]) {
  const rel = url === './' ? 'index.html' : url;
  const bytes = fs.readFileSync(path.join(ROOT, rel));
  // Text files use CRLF in some Windows checkouts and LF on Linux. Hash the
  // normalized content so both platforms produce the same cache version.
  const content = rel.endsWith('.png') ? bytes : Buffer.from(bytes.toString('utf8').replace(/\r\n?/g, '\n'));
  cacheHash.update(rel).update(content);
}
const CACHE_VERSION = 'v' + cacheHash.digest('hex').slice(0, 12);

const swTemplate = `/* AUTO-GENERATED by generate-sw.js — do not hand-edit the precache lists below.
   Run \`node generate-sw.js\` after adding/removing/renaming any path or lesson. */

const CACHE_VERSION = '${CACHE_VERSION}';
const SHELL_CACHE = 'kashsec-shell-' + CACHE_VERSION;
// Keep learner-selected paths across shell updates. Older versioned content
// caches are removed during activation; new saves use this stable name.
const CONTENT_CACHE = 'kashsec-content';
const RUNTIME_CACHE = 'kashsec-runtime-' + CACHE_VERSION;

const SHELL_URLS = ${JSON.stringify(shellUrls, null, 2)};

const DEFERRED_URLS = ${JSON.stringify(deferredUrls, null, 2)};

const LESSON_URLS = ${JSON.stringify(lessonUrls, null, 2)};

const RUNTIME_HOSTS = ['cdn.jsdelivr.net', 'fonts.googleapis.com', 'fonts.gstatic.com'];
const NEVER_CACHE_HOSTS = ['supabase.co'];

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const shellCache = await caches.open(SHELL_CACHE);
    await shellCache.addAll(SHELL_URLS);
    // Deliberately no self.skipWaiting() here — a new SW waits until the page
    // asks it to take over (see the message listener below), so an update
    // never swaps content under a tab that's already open.
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keep = new Set([SHELL_CACHE, CONTENT_CACHE, RUNTIME_CACHE]);
    const names = await caches.keys();
    await Promise.all(names.filter(n => !keep.has(n)).map(n => caches.delete(n)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', event => {
  if (event.data?.type === 'SKIP_WAITING') {
    self.skipWaiting();
    return;
  }
  if (event.data?.type !== 'CACHE_PATH' || !event.ports?.[0]) return;
  const port = event.ports[0];
  const pathId = event.data.pathId;
  const urls = typeof pathId === 'string' && /^[a-z0-9-]+$/.test(pathId)
    ? LESSON_URLS.filter(url => url.startsWith('course/' + pathId + '/')) : [];
  if (!urls.length) {
    port.postMessage({type:'error', message:'Unknown learning path.'});
    return;
  }
  event.waitUntil((async () => {
    const cache = await caches.open(CONTENT_CACHE);
    let saved = 0;
    let failed = 0;
    for (const url of urls) {
      try {
        if (!await cache.match(url)) {
          const response = await fetch(url);
          if (!response.ok) throw new Error('HTTP ' + response.status);
          await cache.put(url, response);
        }
        saved++;
      } catch (_) {
        failed++;
      }
      port.postMessage({type:'progress', saved, failed, total:urls.length});
    }
    port.postMessage({type:'done', saved, failed, total:urls.length});
  })().catch(() => port.postMessage({type:'error', message:'Offline storage is unavailable.'})));
});

async function staleWhileRevalidate(request, cacheName, event) {
  const cache = await caches.open(cacheName);
  const cached = await cache.match(request);
  const networkPromise = fetch(request).then(async response => {
    if (response && response.ok) {
      try { await cache.put(request, response.clone()); } catch (_) { /* quota: serve network response */ }
    }
    return response;
  }).catch(() => null);
  if (event) event.waitUntil(networkPromise);
  return cached || (await networkPromise) || Response.error();
}

async function cacheFirst(request, cacheName) {
  const cache = await caches.open(cacheName);
  const cached = await cache.match(request);
  if (cached) return cached;
  try {
    const response = await fetch(request);
    // Cross-origin script/font responses are usually opaque (status 0) —
    // still cacheable and usable, just not inspectable.
    if (response && (response.ok || response.type === 'opaque')) {
      cache.put(request, response.clone());
    }
    return response;
  } catch (err) {
    return Response.error();
  }
}

async function canonicalNavigation(request, event) {
  const response = await staleWhileRevalidate(request, SHELL_CACHE, event);
  if (response.ok) return response;
  // The individual HTML files are generated for crawlers and direct links.
  // Offline, the cached app shell can render their route from the pathname
  // and fetch the lesson Markdown from the content cache. index.html has a
  // root base URL so its assets still resolve at nested lesson paths.
  return (await caches.match('index.html')) || response;
}

self.addEventListener('fetch', event => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);

  // Never intercept Supabase auth/sync calls — they must always hit the
  // network live, and caching them would be actively wrong.
  if (NEVER_CACHE_HOSTS.some(h => url.hostname.endsWith(h))) return;

  if (url.origin === self.location.origin) {
    const isLesson = LESSON_URLS.some(u => url.pathname.endsWith(u));
    const isCanonicalPage = request.mode === 'navigate' &&
      ((url.pathname.endsWith('.html') &&
        (['/lesson/', '/labs/', '/tools/'].some(prefix => url.pathname.startsWith(prefix)) ||
         ['/faq.html', '/practice.html', '/exam.html'].includes(url.pathname))) ||
       ['/lesson/', '/labs/', '/tools/'].includes(url.pathname) ||
       (url.pathname.startsWith('/lesson/') && url.pathname.endsWith('/')));
    event.respondWith(isCanonicalPage ? canonicalNavigation(request, event) :
      staleWhileRevalidate(request, isLesson ? CONTENT_CACHE : SHELL_CACHE, event));
    return;
  }

  if (RUNTIME_HOSTS.some(h => url.hostname === h || url.hostname.endsWith('.' + h))) {
    event.respondWith(cacheFirst(request, RUNTIME_CACHE));
  }
});
`;

fs.writeFileSync(path.join(ROOT, 'sw.js'), swTemplate);
console.log(`sw.js written — ${shellUrls.length} shell assets, ${lessonUrls.length} lessons available on demand.`);
