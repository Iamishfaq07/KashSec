#!/usr/bin/env node
/*
 * Builds the plain-text body index the in-app search uses to match content,
 * not just titles. Emits TWO tiers:
 *
 *   search-preview.js  first PREVIEW_CAP chars per lesson  (~55 KB gzipped)
 *   search-index.js    first CAP chars per lesson          (~427 KB gzipped)
 *
 * WHY TWO
 * One 427 KB download fired the moment the search overlay opened — including
 * for anyone who opened it, glanced, and pressed Escape, and for anyone using
 * it as a command palette to jump to a page by name, which needs no body text
 * at all. The preview tier covers the opening of every lesson, which is where
 * headings, definitions and key terms live, so it answers most queries on its
 * own; the full index then arrives in the background and deep matches fill in
 * behind it. Nobody pays anything until they actually type.
 *
 * Each entry: { p:pathId, s:subId, n:"N.M", pt:pathTitle, t:subTitle, b:bodyText }
 * Body is stripped of markdown/callout/code syntax and capped for size.
 *
 * Run after lesson content changes:  node generate-search-index.js
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const appJs = fs.readFileSync(path.join(ROOT, 'app.js'), 'utf8');
const m = appJs.match(/const PATHS = \[[\s\S]*?\n\];/);
if (!m) throw new Error('Could not find PATHS array in app.js');
const PATHS = new Function(m[0] + '; return PATHS;')();

const CAP = 2500;         // full index: max body chars per lesson
const PREVIEW_CAP = 400;  // preview index: enough for intro + first headings

function stripMarkdown(md){
  let t = md;
  t = t.replace(/```[\s\S]*?```/g, ' ');          // fenced code
  t = t.replace(/~~~svg[\s\S]*?~~~/g, ' ');        // svg figures
  t = t.replace(/^:::\w+.*$/gm, ' ');              // callout open lines
  t = t.replace(/^:::\s*$/gm, ' ');                // callout close
  t = t.replace(/\?{3}refs[\s\S]*?\?{3}/g, ' ');   // reference blocks
  t = t.replace(/<[^>]+>/g, ' ');                  // any inline HTML
  t = t.replace(/!\[[^\]]*\]\([^)]*\)/g, ' ');     // images
  t = t.replace(/\[([^\]]+)\]\([^)]*\)/g, '$1');   // links -> text
  t = t.replace(/[#>*_`~|]/g, ' ');                // md punctuation
  t = t.replace(/\s+/g, ' ').trim();
  return t;
}

const entries = [];
for (const p of PATHS) {
  for (const s of p.subs) {
    const file = path.join(ROOT, 'course', p.id, s.id + '.md');
    if (!fs.existsSync(file)) continue;
    let body = stripMarkdown(fs.readFileSync(file, 'utf8'));
    if (body.length > CAP) body = body.slice(0, CAP);
    entries.push({ p: p.id, s: s.id, n: `${p.n}.${s.n}`, pt: p.title, t: s.title, b: body });
  }
}

function emit(file, varName, rows, note) {
  const out = `/* AUTO-GENERATED by generate-search-index.js — do not hand-edit.
   ${note} */

const ${varName} = ${JSON.stringify(rows)};
`;
  fs.writeFileSync(path.join(ROOT, file), out);
  return Math.round(Buffer.byteLength(out) / 1024);
}

const previewRows = entries.map(e => ({ ...e, b: e.b.slice(0, PREVIEW_CAP) }));
const previewKb = emit('search-preview.js', 'SEARCH_PREVIEW', previewRows,
  `Short body preview (first ${PREVIEW_CAP} chars per lesson) — the tier loaded first.`);
const fullKb = emit('search-index.js', 'SEARCH_CONTENT', entries,
  'Full plain-text body index for full-text lesson search.');
console.log(`search-preview.js written — ${entries.length} lessons, ${previewKb} KB.`);
console.log(`search-index.js written — ${entries.length} lessons, ${fullKb} KB.`);
